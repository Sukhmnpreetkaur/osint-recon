def _module_icon(module_name: str) -> str:
    """Get an emoji icon for a module."""
    icons = {
        "username_search": "👤",
        "email_recon": "📧",
        "domain_recon": "🌐",
        "phone_lookup": "📱",
        "metadata_extraction": "📄",
        "google_dorks": "🔎",
        "web_scrape": "🕸",
        "geolocation": "📍",
    }
    return icons.get(module_name, "📋")


def save_report(
    findings: list[dict[str, Any]],
    target: str,
    output_dir: str = ".",
    formats: list[str] | None = None,
) -> list[str]:
    """
    Save report in requested formats.
    
    Returns list of saved file paths.
    """
    if formats is None:
        formats = ["json", "html"]

    timestamp = datetime.now(timezone.utc).isoformat()
    safe_target = "".join(c if c.isalnum() or c in "-_." else "_" for c in target)
    date_str = datetime.now().strftime("%Y%m%d_%H%M%S")
    base_name = f"osint_report_{safe_target}_{date_str}"

    report_data = {
        "tool": "OSINT Recon",
        "version": "1.0.0",
        "target": target,
        "timestamp": timestamp,
        "modules": findings,
    }

    saved_files: list[str] = []

    os.makedirs(output_dir, exist_ok=True)

    if "json" in formats:
        json_path = os.path.join(output_dir, f"{base_name}.json")
        with open(json_path, "w", encoding="utf-8") as f:
            json.dump(report_data, f, indent=2, default=str)
        saved_files.append(json_path)
        console.print(f"[green]✓ JSON report saved:[/green] {json_path}")

    if "html" in formats:
        html_path = os.path.join(output_dir, f"{base_name}.html")
        html_content = _build_html_report(report_data)
        with open(html_path, "w", encoding="utf-8") as f:
            f.write(html_content)
        saved_files.append(html_path)
        console.print(f"[green]✓ HTML report saved:[/green] {html_path}")

    return saved_files
